# goal sets used below
_TRAIN = ("calisthenics", "bulking", "weight_loss", "general_fitness")
_ALL = _TRAIN + ("recovery",)


@dataclass(frozen=True, slots=True)
class ExerciseSpec:
    slug: str
    name: str
    category: str
    goals: tuple[str, ...]
    muscles: tuple[str, ...]
    equipment: str
    difficulty: str
    intensity: str
    impact: str
    description: str
    cues: tuple[str, ...]
    contraindications: tuple[str, ...] = ()
    video_slug: str | None = None

    def as_row(self) -> dict[str, Any]:
        """Column values for ``app.models.Exercise`` (JSONB columns as lists; difficulty as a string)."""
        return {
            "slug": self.slug,
            "name": self.name,
            "category": self.category,
            "goals": list(self.goals),
            "muscles": list(self.muscles),
            "equipment": self.equipment,
            "difficulty": self.difficulty,
            "intensity": self.intensity,
            "impact": self.impact,
            "description": self.description,
            "cues": list(self.cues),
            "contraindications": list(self.contraindications),
            "video_slug": self.video_slug,
        }

    @property
    def embedding_text(self) -> str:
        """Text embedded for semantic search: name + description + cues + goals (+ muscles, category)."""
        goals = " ".join(g.replace("_", " ") for g in self.goals)
        return " ".join([self.name, self.description, " ".join(self.cues), goals, " ".join(self.muscles), self.category])


def _ex(slug: str, name: str, category: str, goals: tuple[str, ...], muscles: tuple[str, ...], *, equipment: str = "none",
        difficulty: str = "beginner", intensity: str = "moderate", impact: str = "low", description: str,
        cues: tuple[str, ...], contra: tuple[str, ...] = (), video: str | None = None) -> ExerciseSpec:
    return ExerciseSpec(slug=slug, name=name, category=category, goals=goals, muscles=muscles, equipment=equipment,
                        difficulty=difficulty, intensity=intensity, impact=impact, description=description, cues=cues,
                        contraindications=contra, video_slug=video)


