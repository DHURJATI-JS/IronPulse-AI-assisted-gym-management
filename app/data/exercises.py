"""Exercise library (WP-I) - the canonical catalogue synced into the ``exercises`` table.

Every entry mirrors ``app.models.Exercise``. ``contraindications`` are safety tags - keys of
``app.services.conditions.CONDITION_TAGS`` plus ``"minor"`` - and form the deterministic guardrail that
AI, template and trainer plans are checked against (``app.ai.safety``, ``app.services.live_coach``).

Design rules:

* **Medically conservative.** When an exercise is doubtful for a condition it is flagged: the safety
  filter then swaps it for a safer exercise of the same category, so a flag never empties a plan.
  Heavy barbell lifts are flagged for blood-pressure / heart conditions, hernia, epilepsy (a seizure
  under a loaded bar) and for under-18s (they need a coach and a spotter); impact work is flagged for
  joint conditions, pregnancy and obesity; supine work after the first trimester for pregnancy.
* **Speakable cues.** 3-5 short, complete sentences (<= 90 characters, no symbols or abbreviations):
  the live voice coach reads them aloud.
* **Stable slugs.** Slugs match the built-in fallback libraries of the coach (WP-E2) and the live coach
  (WP-K) wherever the exercise is the same, so stored plans keep their links.

Nothing here touches the database - ``app.services.content.sync_exercises`` upserts it.
"""

