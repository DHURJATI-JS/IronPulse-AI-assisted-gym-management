#!/usr/bin/env bash
# User-space Redis for IronPulse sessions (macOS / Linux) - no sudo, no Docker.
# Installed by "./setup.sh --db runtime" (conda-forge redis-server under ~/.ironpulse/env/bin):
#   data ~/.ironpulse/redis (append-only file + redis.log), password file ~/.ironpulse/redis_password,
#   listens on 127.0.0.1:6379 only. Redis is optional: without it sessions live in PostgreSQL only.
#
# Usage: scripts/runtime_redis.sh start|stop|restart|status|cli [redis-cli args]|logs
# Environment overrides: IRONPULSE_HOME, IRONPULSE_REDIS_PORT
set -euo pipefail

IRONPULSE_HOME="${IRONPULSE_HOME:-$HOME/.ironpulse}"
BIN="$IRONPULSE_HOME/env/bin"
DATA_DIR="$IRONPULSE_HOME/redis"
REDIS_PORT="${IRONPULSE_REDIS_PORT:-6379}"
PW_FILE="$IRONPULSE_HOME/redis_password"
CONF="$DATA_DIR/redis.conf"

say() { printf '[runtime-redis] %s\n' "$*"; }
die() { printf '[runtime-redis] error: %s\n' "$*" >&2; exit 1; }

usage() {
  cat <<'EOF'
User-space Redis (session store) for IronPulse - installed by ./setup.sh --db runtime.

Usage: scripts/runtime_redis.sh <command>
  start            start Redis on 127.0.0.1:6379 (password protected, append-only persistence)
  stop             stop Redis (saves first)
  restart          stop + start
  status           PING the server
  cli [args]       open redis-cli with the password (never shown on the command line)
  logs             follow the Redis log

Files: ~/.ironpulse/redis (data, redis.conf, redis.log), ~/.ironpulse/redis_password
Redis is optional - without it IronPulse keeps sessions in PostgreSQL only.
EOF
}

need_bin() {
  [ -x "$BIN/$1" ] || die "$BIN/$1 not found - install the runtime first: ./setup.sh --db runtime"
}

gen_password() {
  local pw
  pw="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom 2>/dev/null | head -c 32 || true)"
  [ "${#pw}" -ge 24 ] || die "could not generate a random password"
  printf '%s' "$pw"
}

password() {
  # called inside $(...): messages go to stderr so they never end up in the captured password
  if [ ! -s "$PW_FILE" ]; then
    mkdir -p "$IRONPULSE_HOME"
    (umask 077 && gen_password > "$PW_FILE")
    say "generated the Redis password ($PW_FILE)" >&2
  fi
  cat "$PW_FILE"
}

ping_ok() {
  [ -x "$BIN/redis-cli" ] || return 1
  local reply
  reply="$(REDISCLI_AUTH="$(password)" "$BIN/redis-cli" -h 127.0.0.1 -p "$REDIS_PORT" ping 2>/dev/null || true)"
  [ "$reply" = "PONG" ]
}

write_conf() {
  mkdir -p "$DATA_DIR"
  chmod 700 "$DATA_DIR" 2>/dev/null || true
  local pw
  pw="$(password)"
  (
    umask 077
    cat >"$CONF" <<EOF
# generated by scripts/runtime_redis.sh - edits are overwritten on every start
bind 127.0.0.1
port $REDIS_PORT
protected-mode yes
requirepass $pw
dir "$DATA_DIR"
appendonly yes
daemonize yes
pidfile "$DATA_DIR/redis.pid"
logfile "$DATA_DIR/redis.log"
EOF
  )
}

cmd_start() {
  need_bin redis-server
  if ping_ok; then
    say "already running on 127.0.0.1:$REDIS_PORT"
    return 0
  fi
  write_conf
  "$BIN/redis-server" "$CONF"
  local i=0
  while [ "$i" -lt 30 ]; do
    if ping_ok; then
      say "running on 127.0.0.1:$REDIS_PORT (data: $DATA_DIR)"
      return 0
    fi
    sleep 0.3
    i=$((i + 1))
  done
  tail -n 20 "$DATA_DIR/redis.log" >&2 2>/dev/null || true
  die "Redis did not answer PING - see $DATA_DIR/redis.log (is port $REDIS_PORT used by another Redis?)"
}

cmd_stop() {
  need_bin redis-cli
  if ! ping_ok; then
    say "not running"
    return 0
  fi
  REDISCLI_AUTH="$(password)" "$BIN/redis-cli" -h 127.0.0.1 -p "$REDIS_PORT" shutdown >/dev/null 2>&1 || true
  local i=0
  while [ "$i" -lt 30 ] && ping_ok; do
    sleep 0.3
    i=$((i + 1))
  done
  if ping_ok; then
    die "Redis is still running"
  fi
  say "stopped"
}

cmd_status() {
  if [ ! -x "$BIN/redis-server" ]; then
    say "not installed ($BIN) - run ./setup.sh --db runtime (Redis is optional)"
    return 3
  fi
  if ping_ok; then
    say "running - PONG from 127.0.0.1:$REDIS_PORT"
    return 0
  fi
  say "not running - start it with: scripts/runtime_redis.sh start"
  return 3
}

cmd_cli() {
  need_bin redis-cli
  REDISCLI_AUTH="$(password)" exec "$BIN/redis-cli" -h 127.0.0.1 -p "$REDIS_PORT" "$@"
}

cmd_logs() {
  [ -f "$DATA_DIR/redis.log" ] || die "no log yet ($DATA_DIR/redis.log)"
  exec tail -n 100 -f "$DATA_DIR/redis.log"
}

command="${1:-}"
[ $# -gt 0 ] && shift
case "$command" in
  start) cmd_start ;;
  stop) cmd_stop ;;
  restart) cmd_stop; cmd_start ;;
  status) cmd_status ;;
  cli) cmd_cli "$@" ;;
  logs) cmd_logs ;;
  -h|--help|help) usage ;;
  "") usage; exit 2 ;;
  *) usage >&2; die "unknown command: $command" ;;
esac
